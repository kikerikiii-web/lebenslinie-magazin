// Hero Slider Controller
window.initHeroSlider = function() {
    var slides = document.querySelectorAll('.hero-slide');
    var dots = document.querySelectorAll('.slider-dot');
    var prevBtn = document.querySelector('.slider-nav-prev');
    var nextBtn = document.querySelector('.slider-nav-next');
    var currentIndex = 0;
    var timer = null;

    if (!slides.length) return;

    window.goToSlide = function(i) {
        currentIndex = (i + slides.length) % slides.length;
        slides.forEach(function(s, idx) { if (s) s.classList.toggle('active', idx === currentIndex); });
        dots.forEach(function(d, idx) { if (d) d.classList.toggle('active', idx === currentIndex); });
    };

    window.nextSlide = function() { window.goToSlide(currentIndex + 1); };
    window.prevSlide = function() { window.goToSlide(currentIndex - 1); };

    if (nextBtn) nextBtn.onclick = function(e) { e.preventDefault(); window.nextSlide(); };
    if (prevBtn) prevBtn.onclick = function(e) { e.preventDefault(); window.prevSlide(); };
    dots.forEach(function(d, idx) { d.onclick = function(e) { e.preventDefault(); window.goToSlide(idx); }; });

    timer = setInterval(function() { window.nextSlide(); }, 8500);
};

// Partner Slider Controller
window.initPartnerSlider = function() {
    var partnerBoxes = document.querySelectorAll('.partner-slider-sidebar-box');
    if (!partnerBoxes.length) return;

    var partnerIndex = 0;
    var partnerTimer = null;

    window.goToPartnerSlide = function(index) {
        partnerBoxes.forEach(function(box) {
            var slides = box.querySelectorAll('.partner-slide');
            var dots = box.querySelectorAll('.partner-dot');
            var total = slides.length;
            if (!total) return;

            partnerIndex = (index + total) % total;

            slides.forEach(function(s, i) {
                if (s) {
                    s.style.display = (i === partnerIndex) ? 'flex' : 'none';
                    s.classList.toggle('active', i === partnerIndex);
                }
            });

            dots.forEach(function(d, i) {
                if (d) {
                    d.style.background = (i === partnerIndex) ? '#768A76' : '#CBD5E1';
                    d.classList.toggle('active', i === partnerIndex);
                }
            });
        });
    };

    window.nextPartnerSlide = function() { window.goToPartnerSlide(partnerIndex + 1); };
    window.prevPartnerSlide = function() { window.goToPartnerSlide(partnerIndex - 1); };

    partnerTimer = setInterval(function() { window.goToPartnerSlide(partnerIndex + 1); }, 3500);
};

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function() {
        window.initHeroSlider();
        window.initPartnerSlider();
    });
} else {
    window.initHeroSlider();
    window.initPartnerSlider();
}
